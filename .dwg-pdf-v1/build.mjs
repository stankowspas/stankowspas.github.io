import fs from 'node:fs';
import path from 'node:path';
import { build } from 'vite';
const root=process.cwd();
const app=path.join(root,'.dwg-pdf-v1');
const target=path.join(root,'projects/sectron/dwg-to-pdf');
const src=fs.readFileSync(path.join(app,'main.js'),'utf8').replaceAll("'/workers/","'./workers/");
fs.writeFileSync(path.join(app,'main.deploy.js'),src);
const html=fs.readFileSync(path.join(app,'index.html'),'utf8').replace('src="./main.js"','src="./main.deploy.js"');
fs.writeFileSync(path.join(app,'index.deploy.html'),html);
await build({root:app,base:'/projects/sectron/dwg-to-pdf/',publicDir:false,configFile:false,build:{outDir:target,emptyOutDir:true,rollupOptions:{input:path.join(app,'index.deploy.html')}}});
fs.renameSync(path.join(target,'index.deploy.html'),path.join(target,'index.html'));
for(const name of ['style.css','help.html','terms.html'])fs.copyFileSync(path.join(app,name),path.join(target,name));
const mkdir=p=>fs.mkdirSync(path.join(target,p),{recursive:true});mkdir('workers');mkdir('wasm');
const from=(src,dst)=>{const file=path.join(app,'node_modules/@mlightcad',src);if(!fs.existsSync(file))throw Error('Missing runtime asset: '+file);fs.copyFileSync(file,path.join(target,dst))};
from('libredwg-converter/dist/libredwg-parser-worker.js','workers/libredwg-parser-worker.js');
from('libredwg-converter/dist/libredwg-web.wasm','workers/libredwg-web.wasm');
from('cad-simple-viewer/dist/mtext-renderer-worker.js','workers/mtext-renderer-worker.js');
from('libredwg-web/wasm/libredwg-web.js','wasm/libredwg-web.js');
from('libredwg-web/wasm/libredwg-web.wasm','wasm/libredwg-web.wasm');
console.log('Built',target,fs.readdirSync(target));
